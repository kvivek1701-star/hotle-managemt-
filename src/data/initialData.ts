// Helper to calculate payment status accurately
export const calculateBookingFinancials = (booking: Partial<Booking>) => {
  const nights = booking.nights || 1;
  const rate = booking.roomPricePerNight || 0;
  const extraBedCharge = (booking.extraBeds || 0) * (nights * 800);
  const totalRoomCharges = (nights * rate) + extraBedCharge;
  const extraServicesTotal = (booking.extraCharges || []).reduce((sum, item) => sum + item.amount, 0);
  const discount = booking.discount || 0;
  const finalPayable = Math.max(0, totalRoomCharges + extraServicesTotal - discount);
  const totalReceived = (booking.payments || []).reduce((sum, p) => sum + p.amount, 0);
  const remaining = Math.max(0, finalPayable - totalReceived);

  let paymentStatus: Booking['paymentStatus'] = 'payment_pending';
  if (totalReceived >= finalPayable && finalPayable > 0) {
    paymentStatus = 'paid_in_full';
  } else if (totalReceived > 0 && totalReceived < finalPayable) {
    paymentStatus = 'partially_paid';
  } else if (booking.status === 'cancelled') {
    paymentStatus = (booking.refundAmount || 0) > 0 ? 'refunded' : 'cancelled' as any;
  }

  return {
    totalRoomCharges,
    finalPayableAmount: finalPayable,
    totalAmountReceived: totalReceived,
    remainingBalance: remaining,
    paymentStatus,
  };
};

